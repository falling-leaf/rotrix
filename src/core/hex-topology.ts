/** 已解决的六边形三角形棋盘：每个扇区填充对应颜色 */
export function createSolvedHexTriangle(): Board {
  const cells: Cell[] = new Array(54);
  for (let s = 0; s < 6; s++) {
    const color: Color = HEX_COLORS[s];
    for (const idx of SECTOR_CELLS[s]) {
      cells[idx] = { color };
    }
  }
  // dims 不适用于六边形，使用 [54] 标记总数（渲染层特殊处理）
  return { dims: [54], cells };
}

export class HexTriangleTopology implements Topology {
  readonly kind = HEX_TRIANGLE_KIND;

  size(): number {
    return 54;
  }

  /** 19 个旋钮 */
  knobs(): Knob[] {
    return KNOB_CELLS.map((cells, i) => ({
      id: `H${i}`,
      center: KNOB_CENTERS[i],
      cells: [...cells],
      directions: ['CW'],
    }));
  }

  /** 6 个扇区作为目标区域 */
  regions(): Region[] {
    return SECTOR_CELLS.map((cells, i) => ({
      id: `S${i}`,
      cells: [...cells],
    }));
  }
}

/** 单例 */
let _hexInstance: HexTriangleTopology | null = null;
export function hexTriangle(): HexTriangleTopology {
  if (!_hexInstance) _hexInstance = new HexTriangleTopology();
  return _hexInstance;
}
